SELECT id, name, deleted_at
FROM public.courses
WHERE deleted_at IS NOT NULL
  AND id NOT IN ('k01', 'k02', 'k03', 'k04', 'k05', 'k06', 'k07', 'k09', 'k08')
ORDER BY name
LIMIT 30;
